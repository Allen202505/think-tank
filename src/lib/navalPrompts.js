// 模块2：每日知识点生成（迁移 automation-2）
// prev 为上一期 { issue_label, quiz_question, quiz_answer }；无上一期时传 null
// coveredTopics 为已覆盖清单（字符串数组，含基线 + 库里历史）
export function buildDailyPrompt(todayLabel, prev, coveredTopics) {
  const covered = [...new Set([...(coveredTopics || []), ...BASELINE_COVERED_TOPICS])]
    .map((s) => String(s).trim())
    .filter(Boolean);
  const coveredText = covered.length ? covered.join('、') : '（暂无）';
  const prevText = prev && prev.quiz_question
    ? `上一期（${prev.issue_label}）的小测验是：${prev.quiz_question}
参考答案：${prev.quiz_answer || '（未记录，可合理推断）'}`
    : '（没有上一期。⚠️ 本期正文不要写任何"上期揭晓/上期答案"内容，直接从【今日主题】开始。）';

  return `你是「纳瓦尔知识学堂」的主笔，负责每天为用户出一期「每日投资知识点」。

今天是 ${todayLabel}。

${prevText}

本期正文开头：请用 1-2 句揭晓上一期小测验答案，并回扣上一期的深度洞察给一句解析。格式示例：📌 上期揭晓（8-29）：不能——…（回扣上期洞察：…）。若没有上一期则省略此段。

本期要求（严格按此执行）：
1. 推荐 3 个财务或投资指标（知识点），中文，整体精炼（总计约 600-900 字），避免面面俱到和空话。目标是直观理解、有深度、能用于实际分析。
2. 3 个指标尽量围绕同一主题形成递进或互补（例如：现金流→回报率→估值，或盈利质量→成长→估值），开头用一两句说明三者关系（【今日主题】+ 导语）。
3. 每个指标按固定结构：
① 一句话核心：用生活化直觉说明概念；
② 关键公式/关系：只保留必要变量，并解释其经济含义，同时引用真实公开市场数据作实战锚点——选一家有代表性的公司贴出实际数值（如讲净息差时贴招商银行最新净息差、讲市盈率时贴某龙头股当前 PE），标注数据时点与来源（年报/季报/交易所/Wind），数字必须可核查、不得编造，无法实时核实时注明约数或说明口径，数据一行带过、服务理解、不喧宾夺主；
③ 深度洞察：揭示指标真正衡量或隐含的市场预期，纠正一种常见的过度简化理解；
④ 适用场景：什么类型公司、什么问题适合用；
⑤ 缺陷与例外：何时会失真、需要配合看什么，尤其指出行业差异（例如周期股不宜只看市盈率，应结合盈利所处周期、PB/ROE、现金流与资产重置价值）。
每个指标务必配 1 组简短数字例子（简化算例或基于真实数据的计算，一两行带过，如"营业成本 300 亿÷平均存货 60 亿＝5 次，约 73 天"，服务直观理解，不得省略）。
4. 结尾附 1 道小测验题：紧扣当天内容，选择题或简答，只出题、不附答案（本题答案供下一期开头揭晓）。
5. 避免个性化投资建议和具体买卖指令。

请避开以下已讲过的主题/指标，不要重复（可围绕它们的"相邻但未讲过"的角度选新指标）：
${coveredText}

只输出一个 JSON，不要其他内容：
{"title":"今日主题一句话（10-30字）","content":"完整正文（含上期揭晓、今日主题、导语、三个指标、小测验；用空行分段、**加粗** 关键句，不用 # 大标题）","quizQuestion":"本期小测验题目（不附答案）","quizAnswer":"本期小测验参考思路","coveredTopics":["指标1","指标2","指标3"]}
注意：所有字符串里的引号一律用中文引号「」或“”，禁止英文双引号。`;
}
