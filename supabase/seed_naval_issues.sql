**导语**：三个指标依次回答"赚得厚不厚、赚得实不实、买得贵不贵"：毛利率看定价权，净利润现金含量看利润真假，EV/EBITDA 看整盘生意的估值。配合使用，比单看利润表或单看市盈率更完整。

## 1）毛利率

- **一句话核心**：每卖 100 元货，扣掉直接成本后留下多少。像餐厅一份菜定价 50 元、食材只花 20 元，毛利率 60%。
- **关键公式**：毛利率 = (营业收入 − 营业成本) ÷ 营业收入。只扣直接成本，不含销售、研发、利息和税，衡量"产品本身"的赚钱能力与定价权。
- **深度洞察**：高且稳的毛利率是护城河最直接的证据——有定价权、能转嫁成本；毛利率骤降往往先于利润恶化，是早期预警。常见误解是把毛利率当"最终赚多少"用。
- **适用场景**：品牌消费、软件、医药等行业的横向比较；判断提价能力与竞争格局变化。
- **缺陷与例外**：不反映费用与杠杆；零售、航空等重资产行业毛利率天然低，跨行业直接比无意义，须同行比较并看趋势。

## 2）净利润现金含量

- **一句话核心**：账上 1 元利润，有多少真变成了现金，区分"白条利润"与"真金白银"。
- **关键公式**：经营现金流净额 ÷ 净利润。大于 1 说明利润有现金支撑（折旧多、营运资金改善）；长期小于 1，利润沉淀在应收和存货里，质量存疑。
- **深度洞察**：利润是会计口径，现金是到手的钱，该比值衡量"盈利质量"。常见误解是"净利润增长=公司变好"——若现金含量持续小于 1，增长可能是赊销或压货堆出来的。
- **适用场景**：应收高、账期长的行业（工程、ToB 软件）判断利润含金量；配合应收、存货周转一起看。
- **缺陷与例外**：高成长或备货期会阶段性偏低，不能凭单年定论；金融业现金流口径特殊，不适用。

## 3）EV/EBITDA

- **一句话核心**：买下整家公司（股权+净债务）要付几倍"折旧利息税前利润"，像给整盘生意出收购价。
- **关键公式**：EV = 市值 + 净债务；EV/EBITDA = EV ÷ EBITDA。EBITDA 不受资本结构、折旧政策和税率影响，看的是生意本身。
- **深度洞察**：它比市盈率更干净地比较杠杆和折旧政策不同的公司，常用于并购与跨行业对比。常见误解是把它当"免死金牌"——重资产公司的折旧是真实成本，只看 EBITDA 会高估赚钱能力，且开支可被资本化粉饰。
- **适用场景**：资本密集、高杠杆行业（公用事业、电信、基建）的估值比较与并购定价。
- **缺陷与例外**：EBITDA 忽略维持性资本开支，持续重投入的公司会失真；为负时无意义，需结合自由现金流、净债务和行业周期。

## 数字例子

一家公司营收 100、成本 60，毛利率 40%；净利润 10、经营现金流 12，现金含量 1.2，利润"实"；市值 80、净债务 40、EBITDA 20，则 EV/EBITDA = 6 倍。三个数合起来才拼出完整画像。

