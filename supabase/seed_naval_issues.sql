## 一、现金转换周期（CCC）
1）一句话核心：从付款买料、到卖出收款，钱在生意里"转一圈"要多少天——越短，越像用别人的钱做生意。
2）关键公式：CCC = 存货周转天数 + 应收周转天数 − 应付周转天数。前两项是被库存和客户占住的钱，第三项是你能欠供应商的钱。
3）深度洞察：CCC 低常被当成效率高，也可能是"霸道"：靠拖长应付账期挤压供应商。要和同行比相对位置、看趋势，才知真假。
4）适用场景：零售、快消、制造业等重营运资本行业；判断扩张是否烧钱、利润是否变成真现金。
5）缺陷与例外：轻资产高毛利行业（奢侈品、软件）天然 CCC 低，不代表更优；长周期订单行业账期扭曲大，要结合合同进度与现金流看。

## 二、ROE（净资产收益率）
1）一句话核心：股东每投入 1 块钱，一年能赚回多少——自家生意的"理财收益率"。
2）关键公式：ROE = 净利率 × 总资产周转率 × 权益乘数（杜邦分解）。把赚不赚、转得快不快、用了多少杠杆三件事合成一个数。
3）深度洞察：高 ROE 不等于经营好。用杠杆堆出来的 ROE，盈利下滑或融资收紧就会崩塌；靠周转和净利率撑起来的才可持续。它隐含"每 1 元净资产持续创造多少回报"的预期。
4）适用场景：银行、保险、消费等重资本行业；判断长期复利与股东回报天花板。
5）缺陷与例外：周期股盈利高点 ROE 虚高、低点吓人，要结合周期与 PB；回购、减值会扭曲账面权益，宜配 ROIC 与现金流验证。

## 三、股息率
1）一句话核心：花 1 块钱买股票，每年能拿多少现金分红——股票的"利息"。
2）关键公式：股息率 = 每股股息 / 股价。同时含两个信息：公司分多少、市场给多贵。
3）深度洞察：高股息可能是真便宜，也可能是"股息陷阱"——市场预期盈利与分红将下滑，股价先跌、股息率被动抬升。它隐含的是对派息可持续性的定价。
