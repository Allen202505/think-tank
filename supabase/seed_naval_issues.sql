## 自由现金流（FCF）——净利润之外的真金白银

**1）一句话核心**
自由现金流是公司口袋里真正能自由支配的现金，就像月薪扣除房贷和必要开支后真正能存下来的钱；净利润只是账面上的"成绩单"。

**2）关键公式/关系**
FCF = 经营性现金流 − 资本开支。经营现金流是生意本身赚到的现金，资本开支是为维持或扩张生意必须花出去的钱。二者之差才是股东真正能拿走的钱，也是分红、回购和还债的真实来源。

**3）深度洞察**
FCF 衡量的是"造血能力"而非"账面利润"。利润高而 FCF 常年为负，往往意味着钱被应收款、库存或过度投资"占住"了。市场愿意给高估值，隐含预期是未来 FCF 会大幅增长，而不只是利润增长——所以别把"利润高"等同于"有钱"。

**4）适用场景**
适合判断重资产、扩张期公司（制造、零售、扩张中的平台）的分红与回购能否持续、偿债是否安全；也适合横向比较同行业公司的盈利质量。

**5）缺陷与例外**
单期 FCF 受资本开支节奏影响大：某年大建产能导致 FCF 骤降，未必是恶化。不同行业不可直接比较：软件公司资本开支低、FCF 天然高；公用事业、航空资本开支高、FCF 天然低。需配合净利润质量（现金流/净利润比）与资产结构看；周期股在盈利高点时 FCF 最漂亮，却可能即将进入下行，应结合盈利所处周期、PB/ROE 与资产重置价值综合判断。

