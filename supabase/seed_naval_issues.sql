主题：从"钱怎么转"到"股东拿到手"——现金转换周期、ROE、股息率

【上期答案】上期问：流动比率 2.5，但近半存货滞销、应收账期 200 天，短期偿债能力还强吗？不能只看流动比率：它是时点快照，账面资产≠可变现现金。要看速动比率（剔除存货）、应收与存货周转天数、经营现金流——滞销存货和难收回的应收，正是账面安全掩盖的真实风险。

