// 百分制得分 = 10分制评分 × 权重(%) ÷ 10
export function scoreTo100(score10, weightPct) {
  const v = Number(score10) * Number(weightPct) / 10;
  return Math.round(v * 100) / 100;
}

export function totalBand(total) {
  if (Number(total) > 90) return '绝佳买入机会';
  if (Number(total) >= 80) return '稀有买入机会';
  if (Number(total) >= 70) return '合理/优异买入机会';
  return '等待区间';
}

// 供 AI 提示词使用的评分细则文本（保持与 goal-objective 一致）
export function rubricText() {
  return FUNDAMENTAL_CRITERIA.map((c) => {
    const bands = c.bands.map(([top, desc]) => `${top}分：${desc}`).join('；');
    return `第${c.no}条：${c.name}（权重 ${c.weight}%）—— ${bands}。数据来源：${c.source}。`;
  }).join('\n');
}

